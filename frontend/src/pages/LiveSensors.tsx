import React, { useEffect, useState, useCallback } from 'react';
import { getLatestReading, getSensorHistory } from '../services/api';
import type { SensorReading } from '../types';
import { AxisBar, Spinner, MetricCard } from '../components/UI';
import { formatTs, formatNum } from '../utils/helpers';
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip,
  ResponsiveContainer, Legend
} from 'recharts';

const LiveSensors: React.FC = () => {
  const [latest, setLatest] = useState<SensorReading | null>(null);
  const [history, setHistory] = useState<SensorReading[]>([]);
  const [loading, setLoading] = useState(true);

  const fetchData = useCallback(async () => {
    const [lat, hist] = await Promise.all([
      getLatestReading(),
      getSensorHistory(30),
    ]);
    setLatest(lat);
    setHistory(hist.readings.slice().reverse()); // chronological
    setLoading(false);
  }, []);

  useEffect(() => {
    fetchData();
    const t = setInterval(fetchData, 3000);
    return () => clearInterval(t);
  }, [fetchData]);

  const chartData = history.map(r => ({
    t: new Date(r.timestamp).toLocaleTimeString('en-IN', { hour12: false }),
    acc_mag: r.acceleration_magnitude?.toFixed(2),
    gyro_mag: r.gyro_magnitude?.toFixed(2),
    tilt: r.tilt_angle?.toFixed(1),
    speed: r.speed?.toFixed(1),
  }));

  if (loading) return <div style={{ display: 'flex', justifyContent: 'center', padding: 80 }}><Spinner size={32} /></div>;

  const isHardware = latest?.scenario === 'HARDWARE';

  return (
    <div className="page-gap">
      {isHardware ? (
        <div className="alert-box info" style={{ fontSize: 12 }}>
          📡 <strong>LIVE HARDWARE</strong> — Showing readings sent by the ESP32. Updates every 3 seconds.
        </div>
      ) : (
        <div className="alert-box info" style={{ fontSize: 12 }}>
          ⚡ <strong>SIMULATION MODE</strong> — Sensor values are generated by the software simulator.
          Values update every 3 seconds when simulation runs.
        </div>
      )}

      {/* Top Metrics */}
      <div className="grid-4">
        <MetricCard label="Acc Magnitude" value={formatNum(latest?.acceleration_magnitude)} unit="m/s²" accent="blue" icon="💥" />
        <MetricCard label="Gyro Magnitude" value={formatNum(latest?.gyro_magnitude)} unit="°/s" accent="purple" icon="🌀" />
        <MetricCard label="Tilt Angle" value={formatNum(latest?.tilt_angle, 1)} unit="degrees" accent="cyan" icon="📐" />
        <MetricCard label="Speed" value={formatNum(latest?.speed, 1)} unit="km/h" accent="green" icon="🚀" />
      </div>

      {/* Axis Detail */}
      <div className="grid-2">
        <div className="card">
          <div className="card-header">
            <div className="card-title">📊 Accelerometer (m/s²)</div>
            {latest && <span style={{ fontSize: 11, color: 'var(--text-muted)', fontFamily: 'JetBrains Mono' }}>{formatTs(latest.timestamp)}</span>}
          </div>
          {latest ? (
            <>
              <AxisBar label="X" value={latest.accel_x} max={30} color="#ef4444" unit=" m/s²" />
              <AxisBar label="Y" value={latest.accel_y} max={30} color="#10b981" unit=" m/s²" />
              <AxisBar label="Z" value={latest.accel_z} max={30} color="#3b82f6" unit=" m/s²" />
              <div style={{ marginTop: 12, paddingTop: 12, borderTop: '1px solid var(--border-subtle)' }}>
                <AxisBar label="M" value={latest.acceleration_magnitude ?? 0} max={50} color="#f59e0b" unit=" m/s²" />
              </div>
            </>
          ) : <div style={{ color: 'var(--text-muted)', padding: '20px 0', textAlign: 'center' }}>No data — run simulation</div>}
        </div>

        <div className="card">
          <div className="card-header">
            <div className="card-title">🌀 Gyroscope (°/s)</div>
          </div>
          {latest ? (
            <>
              <AxisBar label="X" value={latest.gyro_x} max={250} color="#ef4444" unit=" °/s" />
              <AxisBar label="Y" value={latest.gyro_y} max={250} color="#10b981" unit=" °/s" />
              <AxisBar label="Z" value={latest.gyro_z} max={250} color="#3b82f6" unit=" °/s" />
              <div style={{ marginTop: 12, paddingTop: 12, borderTop: '1px solid var(--border-subtle)' }}>
                <AxisBar label="M" value={latest.gyro_magnitude ?? 0} max={400} color="#8b5cf6" unit=" °/s" />
              </div>
            </>
          ) : <div style={{ color: 'var(--text-muted)', padding: '20px 0', textAlign: 'center' }}>No data — run simulation</div>}
        </div>
      </div>

      {/* Other sensors */}
      <div className="grid-3">
        <div className="card">
          <div className="card-title" style={{ marginBottom: 16 }}>📐 Tilt Angle</div>
          {latest ? (
            <>
              <div style={{ fontSize: 36, fontWeight: 900, fontFamily: 'JetBrains Mono', color: latest.tilt_angle && latest.tilt_angle > 45 ? '#f97316' : '#06b6d4' }}>
                {formatNum(latest.tilt_angle, 1)}°
              </div>
              <div style={{ marginTop: 12 }}>
                <AxisBar label="" value={latest.tilt_angle ?? 0} max={90} color="#06b6d4" unit="°" />
              </div>
              <div style={{ fontSize: 11, color: 'var(--text-muted)', marginTop: 8 }}>Prototype threshold: 45°</div>
            </>
          ) : <div style={{ color: 'var(--text-muted)', padding: '20px 0', textAlign: 'center' }}>No data</div>}
        </div>

        <div className="card">
          <div className="card-title" style={{ marginBottom: 16 }}>🍺 Alcohol Sensor</div>
          {latest ? (
            <>
              <div style={{ fontSize: 36, fontWeight: 900, fontFamily: 'JetBrains Mono', color: latest.alcohol > 0.08 ? '#ef4444' : '#10b981' }}>
                {formatNum(latest.alcohol, 3)}
              </div>
              <div style={{ marginTop: 8, fontSize: 12, color: 'var(--text-muted)' }}>BAC equivalent</div>
              <div style={{ marginTop: 12, padding: '8px 12px', borderRadius: 6, background: latest.alcohol > 0.08 ? 'rgba(239,68,68,0.1)' : 'rgba(16,185,129,0.1)', fontSize: 12, color: latest.alcohol > 0.08 ? '#fca5a5' : '#6ee7b7', fontWeight: 600 }}>
                {latest.alcohol > 0.08 ? '⚠️ ABOVE LEGAL LIMIT' : '✅ Below legal limit'}
              </div>
              <div style={{ fontSize: 11, color: 'var(--text-muted)', marginTop: 8 }}>Prototype threshold: 0.08</div>
            </>
          ) : <div style={{ color: 'var(--text-muted)', padding: '20px 0', textAlign: 'center' }}>No data</div>}
        </div>

        <div className="card">
          <div className="card-title" style={{ marginBottom: 16 }}>📍 GPS {isHardware ? '(Live)' : '(Simulated)'}</div>
          {latest ? (
            latest.latitude != null && latest.longitude != null ? (
              <>
                <div style={{ fontFamily: 'JetBrains Mono', fontSize: 13, color: '#10b981', lineHeight: 2 }}>
                  <div>Lat: {formatNum(latest.latitude, 6)}</div>
                  <div>Lon: {formatNum(latest.longitude, 6)}</div>
                </div>
                {isHardware && (
                  <a
                    href={`https://www.google.com/maps?q=${latest.latitude},${latest.longitude}`}
                    target="_blank"
                    rel="noreferrer"
                    style={{ display: 'inline-block', marginTop: 10, fontSize: 12, color: '#38bdf8' }}
                  >
                    Open in Google Maps
                  </a>
                )}
                <div style={{ marginTop: 12, fontSize: 11, color: 'var(--text-muted)', padding: '8px 10px', borderRadius: 6, background: 'rgba(245,158,11,0.08)', border: '1px solid rgba(245,158,11,0.2)' }}>
                  {isHardware
                    ? '🛰️ Position from the NEO-6M GPS module.'
                    : '⚡ SOFTWARE SIMULATION — GPS accuracy claims require real hardware.'}
                </div>
              </>
            ) : (
              <div style={{ fontSize: 12, color: '#fcd34d', padding: '10px 12px', borderRadius: 6, background: 'rgba(245,158,11,0.08)', border: '1px solid rgba(245,158,11,0.2)' }}>
                ⚠️ No GPS fix yet. Take the module near a window or outside with a clear view of the sky.
              </div>
            )
          ) : <div style={{ color: 'var(--text-muted)', padding: '20px 0', textAlign: 'center' }}>No data</div>}
        </div>
      </div>

      {/* Chart */}
      {chartData.length > 1 && (
        <div className="card">
          <div className="card-header">
            <div className="card-title">📈 Sensor History (Last 30 Readings)</div>
          </div>
          <ResponsiveContainer width="100%" height={240}>
            <LineChart data={chartData} margin={{ top: 4, right: 16, bottom: 4, left: 0 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" />
              <XAxis dataKey="t" tick={{ fill: '#475569', fontSize: 10 }} interval="preserveStartEnd" />
              <YAxis tick={{ fill: '#475569', fontSize: 10 }} />
              <Tooltip contentStyle={{ background: '#111827', border: '1px solid rgba(255,255,255,0.1)', borderRadius: 8, fontSize: 12 }} />
              <Legend wrapperStyle={{ fontSize: 12, color: '#94a3b8' }} />
              <Line type="monotone" dataKey="acc_mag" name="Acc Mag" stroke="#f59e0b" dot={false} strokeWidth={2} />
              <Line type="monotone" dataKey="gyro_mag" name="Gyro Mag" stroke="#8b5cf6" dot={false} strokeWidth={2} />
              <Line type="monotone" dataKey="tilt" name="Tilt°" stroke="#06b6d4" dot={false} strokeWidth={1.5} />
            </LineChart>
          </ResponsiveContainer>
        </div>
      )}
    </div>
  );
};

export default LiveSensors;